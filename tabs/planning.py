"""Tab 3 - Project Planning & Real Estate Valuation."""
import urllib.parse
import streamlit as st

from core.config import LOCATION_TIERS, MILESTONES, STRUCTURE_TYPES
from core.valuation import compute_valuation, format_inr, render_prompt
from ui.components import show_metrics


def render() -> None:
    st.subheader("📐 Planning & Real Estate Valuation")
    st.caption("Indicative budget, asset valuation and material requirements in INR. Rates are editable in core/config.py.")

    c1, c2 = st.columns(2)
    structure = c1.selectbox("Structure type", list(STRUCTURE_TYPES), key="plan_struct")
    tier = c2.selectbox("Location tier", list(LOCATION_TIERS), index=1, key="plan_tier")
    c3, c4 = st.columns(2)
    sqft = c3.number_input("Built-up area (sq ft)", min_value=100, max_value=5_000_000, value=2500, step=100, key="plan_sqft")
    completion = c4.slider("Completion (%)", 0, 100, 40, key="plan_pct")

    try:
        v = compute_valuation(structure, sqft, tier, completion)
    except Exception as exc:
        st.error(f"Calculation error: {exc}")
        return

    show_metrics([
        ("Total project budget", format_inr(v.total_budget), f"₹{v.cost_per_sqft:,.0f}/sq ft incl. 8% contingency"),
        ("Capex incurred", format_inr(v.capex_incurred), f"Remaining {format_inr(v.remaining_budget)}"),
        ("Current asset value", format_inr(v.current_asset_value), f"Finished: {format_inr(v.finished_market_value)}"),
        ("Value vs. capex", format_inr(v.equity_gain), "Asset value minus spend"),
    ])
    st.write("")
    m1, m2 = st.columns(2)
    with m1:
        show_metrics([
            ("Steel (TMT)", f"{v.steel_required_tonnes:,.1f} t", f"{v.steel_consumed_tonnes:,.1f} t used"),
            ("Cement", f"{v.cement_required_bags:,} bags", f"{v.cement_consumed_bags:,} used"),
        ])
    with m2:
        show_metrics([("Current milestone", v.current_milestone, f"{completion}% complete")])

    st.markdown("#### Milestone progress")
    st.progress(completion / 100)
    cols = st.columns(len(MILESTONES))
    for col, (lo, hi, name) in zip(cols, MILESTONES):
        done = completion >= hi
        col.markdown(f"{'✅' if done else '🔹' if completion >= lo else '⬜'} **{name}**<br>"
                     f"<span style='color:#64748B;font-size:.8rem'>{lo}-{hi}%</span>", unsafe_allow_html=True)

    st.markdown("#### 🏗️ Conceptual 3D rendering (Pollinations AI)")
    prompt = st.text_area("Rendering prompt", render_prompt(structure, tier, completion, int(sqft)),
                          height=90, key=f"plan_prompt_{structure}_{tier}_{completion}_{int(sqft)}")
    if st.button("Generate rendering", key="plan_render"):
        st.session_state["render_url"] = (
            "https://image.pollinations.ai/prompt/" + urllib.parse.quote(prompt) +
            "?width=1024&height=640&model=flux&nologo=true")
    if "render_url" in st.session_state:
        st.image(st.session_state["render_url"], caption="AI concept render (illustrative only)",
                 use_container_width=True)
        st.caption("Image is generated by an external service and may take a few seconds to load.")
    st.markdown('<div class="disclaimer">Figures are planning-level estimates, not a certified valuation or BOQ.</div>',
                unsafe_allow_html=True)
